const assert=require('node:assert/strict');
const {initialTab,nextAction,productLabel,preciseTime,draftState}=require('../app/static/workflow-core.js');
const rows=[{id:1,start:.18,end:.54,text:'哥哥。',zh:''}];
const p={id:'a',goal:'transcribe',segments:rows,outputs:{},edit_revision:3,content_version:'base'};
assert.equal(initialTab(p),'subtitles');
assert.deepEqual(nextAction(p,rows,'subtitles',false),{download:'source',label:'导出原文 SRT'});
assert.equal(nextAction({...p,goal:'dub'},rows,'subtitles',false).stage,'translate');
assert.equal(nextAction({...p,goal:'dub'},rows,'voices',false).tab,'subtitles');
const translated=rows.map(r=>({...r,zh:'Hi.'}));
assert.equal(nextAction({...p,goal:'translate'},translated,'subtitles',false).download,'translation');
assert.equal(nextAction({...p,goal:'dub'},translated,'voices',false).tab,'voices');
assert.equal(nextAction({...p,goal:'dub'},translated,'voices',true).stage,'dub');
assert.equal(nextAction({...p,goal:'dub',outputs:{audio:'dub.wav'}},translated,'voices',true).tab,'export');
assert.equal(productLabel({...p,workflow:{code:'source_ready'}}),'原文字幕可导出');
assert.equal(productLabel({...p,goal:'dub',status:'done',workflow:{code:'source_ready'}}),'原文已识别');
assert.equal(productLabel(p),'原文字幕可导出');
assert.equal(productLabel({...p,workflow:{code:'needs_source'}}),'原文字幕可导出');
assert.equal(productLabel({...p,segments:translated}),'译文字幕可导出');
assert.equal(productLabel({goal:'transcribe',workflow:{code:'source_ready'}}),'原文字幕可导出');
assert.equal(preciseTime(.18),'00:00.18');assert.equal(preciseTime(.54),'00:00.54');
assert.equal(preciseTime(59.999),'01:00.00');
const draft={version:1,id:'a',revision:3,content_version:'base',rows:[{...rows[0],text:'草稿'}]};
assert.equal(draftState(draft,p),'recover');
assert.equal(draftState(draft,{...p,edit_revision:4}),'conflict');
assert.equal(draftState(draft,{...p,content_version:'changed'}),'conflict');
assert.equal(draftState(draft,{...p,id:'b'}),'none');
assert.equal(draftState({...draft,rows},p),'saved');
console.log('Project goals, primary actions, product states, precise timing and draft version conflicts: OK');
