const assert=require('node:assert/strict'),crypto=require('node:crypto');
const {split,merge,timing,basis,History}=require('../app/static/subtitle-tools-core.js');
const a={id:17,start:.18,end:2.54,text:'重庆你好，今天去哪里？',zh:'Hello Chongqing, where are we going?',speaker:'speaker_1',review_status:'checked',review_signature:'old'};
const b={id:2,start:3,end:5,text:'去成都。',zh:'To Chengdu.',speaker:'speaker_1'};
const rows=[a,b],before=JSON.stringify(rows);
const divided=split(rows,0,5,1.2,15);
assert.equal(JSON.stringify(rows),before);
assert.deepEqual(divided.map(r=>r.id),[17,18,2]);
assert.equal(divided[0].text+divided[1].text,a.text);
assert.equal(divided[0].zh+divided[1].zh,a.zh);
assert.equal(divided[0].end,divided[1].start);
assert.equal(divided[0].review_status,undefined);assert.equal(divided[1].review_status,undefined);
assert.equal(merge(divided,0)[0].text,divided[0].text+'\n'+divided[1].text);
for(const args of [[rows,0,0,1,5],[rows,0,5,.18,5],[rows,0,5,1,0]])assert.throws(()=>split(...args));
assert.throws(()=>split([{...a,text:'a😀b'}],0,2,1.2,15));
assert.throws(()=>merge([a,{...b,speaker:'speaker_2'}],0));
assert.throws(()=>merge([a,{...b,emotion:'angry'}],0));
assert.throws(()=>merge([a,{...b,zh:''}],0));
assert.throws(()=>merge(rows,1));
assert.throws(()=>timing(rows,0,-1,2,6));
assert.throws(()=>timing(rows,0,4,5,6));
assert.throws(()=>timing(rows,1,2,8,6));
const changed=timing(rows,0,.2,2.5,6);assert.equal(changed[0].review_status,undefined);
assert.deepEqual(timing(rows,0,a.start,a.end,6),rows);
const history=new History();history.push('project:1',rows,divided,0);
assert.deepEqual(history.move('undo',divided).rows,rows);
assert.deepEqual(history.move('redo',rows).rows,divided);
history.sync('project:1',divided.map((r,i)=>i? r:{...r,text:'typed after split'}));assert.equal(history.undoItems.length,0);
history.push('project:1',rows,divided,0);history.sync('project:2',divided);assert.equal(history.undoItems.length,0);
assert.equal(crypto.createHash('sha256').update(basis({text:'重庆😀',zh:'',speaker:'speaker_1',start:.18,end:.54})).digest('hex'),'f0ef0a2dab9e0427444ba0e690846b4984a67f257ba6104dd514d9e0ae0f907b');
console.log('Subtitle split/merge, translated cursors, timing order, Unicode, stale undo and human review signatures: OK');
